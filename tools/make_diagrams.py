def double_slit():
    W, H = 960, 540
    bx, sx = 250, 750                       # barrier and screen x
    yc = 260; d = 100; S1 = (bx, yc - d / 2); S2 = (bx, yc + d / 2); R = sx - bx
    lam = 8.0; dy = lam * R / d             # fringe spacing in pixels
    b = []
    for y in (200, 260, 320):               # incoming plane wave
        b.append(arrow((40, y), (200, y), "@aqua@", 3))
    b.append(line((215, 175), (215, 345), "@aqua@", 1.5, "3 5"))
    b += [f'<rect x="{bx-5}" y="40" width="10" height="{S1[1]-5-40:.0f}" fill="@fg@"/>',
          f'<rect x="{bx-5}" y="{S1[1]+5:.0f}" width="10" height="{S2[1]-5-S1[1]-5:.0f}" fill="@fg@"/>',
          f'<rect x="{bx-5}" y="{S2[1]+5:.0f}" width="10" height="{480-S2[1]-5:.0f}" fill="@fg@"/>',
          line((sx, 40), (sx, 480), "@fg@", 4)]
    # intensity strip on the screen and I(y) curve
    for y in range(40, 480, 2):
        I = math.cos(math.pi * (y + 1 - yc) / dy) ** 2
        b.append(f'<rect x="{sx+6}" y="{y}" width="26" height="2" fill="@yellow@" fill-opacity="{I:.2f}"/>')
    pts = " ".join(f"{sx+44+I*62:.1f},{y}" for y in range(40, 481, 2)
                   for I in [math.cos(math.pi * (y - yc) / dy) ** 2])
    b.append(f'<polyline points="{pts}" fill="none" stroke="@yellow@" stroke-width="2.2"/>')
    b.append(text(sx + 75, 28, "I(y)", 18, "@yellow@", "middle", bold=True))
    # geometry of the first bright fringe (m = 1)
    P = (sx, yc - dy); P0 = (sx, yc)
    b += [ray(S1, P, "@aqua@", 2.6), ray(S2, P, "@aqua@", 2.6),
          line(S1, P0, "@muted@", 1.6, "7 6"), line(S2, P0, "@muted@", 1.6, "7 6")]
    u = unit(P[0] - S2[0], P[1] - S2[1])                    # path difference construction
    t = (S1[0] - S2[0]) * u[0] + (S1[1] - S2[1]) * u[1]
    Fq = pt(S2, u, t)
    b += [line(S1, Fq, "@orange@", 2, "4 3"), line(S2, Fq, "@orange@", 4.2)]
    b.append(text(Fq[0] + 4, Fq[1] + 38, "Δr = d sin θ", 17, "@orange@"))
    # fringe marks: tick on the screen, label to the right of the intensity curve
    for mth in (-2, -1, 0, 1, 2):
        y = yc - mth * dy                      # m = +1 is the first bright fringe ABOVE the centre
        b += [line((sx - 12, y), (sx, y), "@fg@", 2.5),
              text(sx + 116, y + 6, "m = " + str(mth).replace("-", "−"), 15, "@muted@")]
    # dimensions
    b += [dimension((bx - 38, S1[1]), (bx - 38, S2[1])), sym(bx - 48, yc + 7, "d", None, 22, "@fg@", "end"),
          dimension((bx, 508), (sx, 508)), sym((bx + sx) / 2, 500, "R", None, 22, "@fg@", "middle"),
          line((bx, 482), (bx, 516), "@muted@", 1.2, "4 4"), line((sx, 482), (sx, 516), "@muted@", 1.2, "4 4"),
          dimension((sx - 34, yc - dy), (sx - 34, yc), "@yellow@"), sym(sx - 44, yc - dy / 2 + 7, "Δy", None, 20, "@yellow@", "end")]
    b += [text(bx + 20, 66, "Δy = λR / d", 22, "@yellow@", bold=True),
          text(bx + 20, 96, "yₘ = m λ R / d", 22, "@yellow@", bold=True),
          text(bx + 20, 124, "bright fringes: d sin θ = m λ", 16, "@muted@"),
          text(40, 150, "coherent", 16, "@aqua@"), text(40, 170, "light", 16, "@aqua@"),
          text(bx, 30, "double slit", 16, "@muted@", "middle"), text(sx, 30, "screen", 16, "@muted@", "middle")]
    write("double_slit", W, H, b)

# ----------------------------------------------------------------------------- 6. prism
def refract(d, n, eta):
    """Vector form of Snell's law. n: unit normal pointing against d. eta = n1/n2."""
    cosi = -(n[0] * d[0] + n[1] * d[1])
    k = 1 - eta * eta * (1 - cosi * cosi)
    if k < 0: return None
    c = eta * cosi - math.sqrt(k)
    return (eta * d[0] + c * n[0], eta * d[1] + c * n[1])

def intersect(p, d, q, e):
    """Intersection of lines p + s d and q + t e."""
    det = d[0] * (-e[1]) - d[1] * (-e[0])
    s = ((q[0] - p[0]) * (-e[1]) - (q[1] - p[1]) * (-e[0])) / det
    return (p[0] + s * d[0], p[1] + s * d[1])

def prism():
    W, H = 800, 520
    n = 1.5; th1 = 50.0
    Ap, Lf, Rt = (400, 80), (250, 340), (550, 340)
    eL = unit(Lf[0] - Ap[0], Lf[1] - Ap[1]); eR = unit(Rt[0] - Ap[0], Rt[1] - Ap[1])
    nL = (-0.8660254, -0.5); nR = (0.8660254, -0.5)             # outward normals
    A = math.degrees(math.acos(eL[0] * eR[0] + eL[1] * eR[1]))
    P1 = (Ap[0] + 0.55 * (Lf[0] - Ap[0]), Ap[1] + 0.55 * (Lf[1] - Ap[1]))
    ang = math.radians(30 - th1)                                # inward normal is 30° below +x
    d0 = (math.cos(ang), math.sin(ang))
    d1 = refract(d0, nL, 1 / n)
    P2 = intersect(P1, d1, Ap, eR)
    d2 = refract(d1, (-nR[0], -nR[1]), n)
    X = intersect(P1, d0, P2, d2)
    delta = math.degrees(math.acos(max(-1, min(1, d0[0] * d2[0] + d0[1] * d2[1]))))
    th4 = math.degrees(math.acos(-(d2[0] * -nR[0] + d2[1] * -nR[1])))   # exit angle w.r.t. the normal
    b = [f'<polygon points="{Ap[0]},{Ap[1]} {Lf[0]},{Lf[1]} {Rt[0]},{Rt[1]}" fill="@blue@" fill-opacity="0.22" stroke="@blue@" stroke-width="4" stroke-linejoin="round"/>',
         line(pt(P1, nL, 95), pt(P1, nL, -60), "@muted@", 2, "8 6"), line(pt(P2, nR, 95), pt(P2, nR, -60), "@muted@", 2, "8 6")]
    S = pt(P1, d0, -170); E = pt(P2, d2, 200)
    b += [ray(S, P1, "@red@", 4), ray(P1, P2, "@yellow@", 4), ray(P2, E, "@green@", 4),
          line(P1, X, "@muted@", 2, "3 6"), line(X, pt(X, d0, -0), "@muted@", 2)]
    b.append(line(X, P2, "@muted@", 2, "3 6"))
    # angles
    b += [arc(P1, nL, (-d0[0], -d0[1]), 52, "@red@"), arc(P2, nR, d2, 52, "@green@"),
          arc(Ap, eL, eR, 50, "@orange@"), arc(X, d0, d2, 58, "@orange@")]
