#!/usr/bin/env python3
"""Generates the optical-setup diagrams in assets/diagrams/*.svg.

All geometry is computed here (Snell's law, thin-lens equation, mirror equation, prism
refraction), so the pictures are physically consistent. Colours are placeholders such as
@red@ / @fg@ - the application replaces them with the active Gruvbox theme at run time, so
the same SVG works in dark and light mode and scales without losing quality.

Run:  python3 tools/make_diagrams.py
"""
import math, os

OUT = os.path.join(os.path.dirname(__file__), "..", "assets", "diagrams")
SANS = "DejaVu Sans, Arial, Helvetica, sans-serif"
SERIF = "DejaVu Serif, Times New Roman, serif"

# ----------------------------------------------------------------------------- helpers
def f(v): return f"{v:.1f}"
def signed(v, nd=2):
    return ("−" if v < 0 else "") + f"{abs(v):.{nd}f}"
def unit(dx, dy):
    n = math.hypot(dx, dy); return dx / n, dy / n
def pt(p, d, L): return (p[0] + d[0] * L, p[1] + d[1] * L)

def line(p, q, color="@fg@", w=2.0, dash=None, opacity=None):
    extra = (f' stroke-dasharray="{dash}"' if dash else "") + (f' stroke-opacity="{opacity}"' if opacity else "")
    return f'<line x1="{f(p[0])}" y1="{f(p[1])}" x2="{f(q[0])}" y2="{f(q[1])}" stroke="{color}" stroke-width="{w}" stroke-linecap="round"{extra}/>'

def head(tip, d, color, size=15):
    """Solid arrow head whose tip is at `tip`, pointing along unit vector d."""
    bx, by = tip[0] - d[0] * size, tip[1] - d[1] * size
    nx, ny = -d[1], d[0]
    a = (bx + nx * size * 0.38, by + ny * size * 0.38)
    b = (bx - nx * size * 0.38, by - ny * size * 0.38)
    return f'<polygon points="{f(tip[0])},{f(tip[1])} {f(a[0])},{f(a[1])} {f(b[0])},{f(b[1])}" fill="{color}"/>'

def ray(p, q, color, w=3.5, at=0.55, dash=None):
    """Line p->q with an arrow head at fraction `at` of the way (rays are drawn with a mid arrow)."""
    d = unit(q[0] - p[0], q[1] - p[1])
    L = math.hypot(q[0] - p[0], q[1] - p[1])
    tip = pt(p, d, L * at + 7)
    return line(p, q, color, w, dash) + head(tip, d, color, 14)

def arrow(p, q, color="@fg@", w=2.5):
    d = unit(q[0] - p[0], q[1] - p[1])
    return line(p, pt(q, d, -10), color, w) + head(q, d, color, 14)

def dimension(p, q, color="@muted@", w=2):
    """Double-headed dimension arrow."""
    d = unit(q[0] - p[0], q[1] - p[1])
    return line(pt(p, d, 9), pt(q, d, -9), color, w) + head(q, d, color, 11) + head(p, (-d[0], -d[1]), color, 11)

def text(x, y, s, size=18, color="@fg@", anchor="start", italic=False, bold=False, serif=False):
    fam = SERIF if (italic or serif) else SANS
    st = ' font-style="italic"' if italic else ""
    wt = ' font-weight="bold"' if bold else ""
    return (f'<text x="{f(x)}" y="{f(y)}" font-family="{fam}" font-size="{size}" fill="{color}" '
            f'text-anchor="{anchor}"{st}{wt}>{s}</text>')

def sym(x, y, base, sub=None, size=22, color="@fg@", anchor="start", bold=False):
    """Italic symbol with an optional subscript (tspan)."""
    s = base + (f'<tspan dy="{size*0.28:.1f}" font-size="{size*0.68:.1f}">{sub}</tspan>' if sub else "")
    return text(x, y, s, size, color, anchor, italic=True, bold=bold)

def arc(center, u, v, r, color, w=2.5):
    """Arc of radius r around `center` from direction u to direction v (unit vectors, screen coords)."""
    p, q = pt(center, u, r), pt(center, v, r)
    sweep = 1 if (u[0] * v[1] - u[1] * v[0]) > 0 else 0
    return (f'<path d="M {f(p[0])} {f(p[1])} A {r} {r} 0 0 {sweep} {f(q[0])} {f(q[1])}" '
            f'fill="none" stroke="{color}" stroke-width="{w}" stroke-linecap="round"/>')

def mid_dir(u, v):
    return unit(u[0] + v[0], u[1] + v[1])

def dot(p, r=4.5, color="@fg@"):
    return f'<circle cx="{f(p[0])}" cy="{f(p[1])}" r="{r}" fill="{color}"/>'

def svg(w, h, body, name):
    return (f'<?xml version="1.0" encoding="UTF-8"?>\n<!-- {name}: generated by tools/make_diagrams.py - do not edit by hand -->\n'
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}">\n'
            + "\n".join(body) + "\n</svg>\n")

def write(name, w, h, body):
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, name + ".svg"), "w", encoding="utf-8") as fh:
        fh.write(svg(w, h, body, name))

