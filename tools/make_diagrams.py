# ----------------------------------------------------------------------------- 2. total internal reflection
def tir():
    W, H = 900, 540
    O = (400, 250); n1, n2 = 1.5, 1.0
    crit = math.degrees(math.asin(n2 / n1)); L = 215
    b = [f'<rect x="0" y="0" width="{W}" height="250" fill="@blue@" fill-opacity="0.06"/>',
         f'<rect x="0" y="250" width="{W}" height="290" fill="@blue@" fill-opacity="0.22"/>',
         line((40, 250), (860, 250), "@fg@", 3.5),
         line((400, 40), (400, 520), "@muted@", 2, "9 7"),
         text(412, 58, "Normal", 17, "@muted@")]
    cases = [(25.0, "θ₁ &lt; θc", "@red@"), (crit, "θ₁ = θc", "@red@"), (60.0, "θ₁ &gt; θc", "@red@")]
    for ang, lbl, col in cases:
        t = math.radians(ang)
        inc = (-math.sin(t), math.cos(t))          # incident ray comes from below-left (inside the glass)
        ref = (math.sin(t), math.cos(t))
        S = pt(O, inc, L); E = pt(O, ref, L * (0.7 if ang < 30 else 1.0))
        b += [ray(S, O, col), ray(O, E, "@blue@", 3.5)]
        b.append(text(S[0] - 8, S[1] + 5, lbl, 19, "@red@", "end", bold=True))
    # partial case: refracted ray into the air (bends away from the normal)
    t = math.radians(25.0); t2 = math.asin(n1 * math.sin(t) / n2)
    E = pt(O, (math.sin(t2), -math.cos(t2)), 235)
    b += [ray(O, E, "@green@"), text(E[0] + 8, E[1] + 4, "refracted ray", 18, "@green@")]
    # critical case: refracted ray grazes the interface (90 degrees)
    b += [ray(O, (O[0] + 235, O[1] - 4), "@green@", 3.5, 0.6, "10 6"),
          text(O[0] + 240, O[1] + 20, "refracted at 90°", 17, "@green@")]
    # total internal reflection label
    t = math.radians(60.0); E = pt(O, (math.sin(t), math.cos(t)), L)
    b.append(text(E[0] + 10, E[1] + 6, "Total internal reflection", 17, "@orange@", bold=True))
    b += [text(22, 40, "Air   n₂ = 1.00", 20), text(22, 522, "Glass   n₁ = 1.50", 20),
          text(878, 470, f"sin θc = n₂ / n₁   →   θc = {crit:.1f}°", 21, "@yellow@", "end", bold=True),
          text(878, 498, "possible only when light goes from n₁ to a smaller n₂", 16, "@muted@", "end"), dot(O)]
    write("tir", W, H, b)

