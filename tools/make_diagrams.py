def mirror():
    W, H = 900, 480
    ax = 240; R = 300; Vx = 700; Cx = Vx - R; fl = R / 2; Fx = Vx - fl
    s = 350; ox = Vx - s; hobj = 80
    sp = 1 / (1 / fl - 1 / s); m = -sp / s; ix = Vx - sp
    tip = (ox, ax - hobj); itip = (ix, ax - m * hobj)
    a = math.radians(34)
    top = (Cx + R * math.cos(a), ax - R * math.sin(a)); bot = (top[0], ax + R * math.sin(a))
    b = [line((30, ax), (860, ax), "@muted@", 2)]
    for k in range(-4, 5):                      # hatching behind the mirror
        ang = math.radians(k * 8)
        p = (Cx + R * math.cos(ang), ax + R * math.sin(ang))
        b.append(line(p, (p[0] + 15 * math.cos(ang), p[1] + 15 * math.sin(ang)), "@blue@", 2))
    b.append(f'<path d="M {f(top[0])} {f(top[1])} A {R} {R} 0 0 1 {f(bot[0])} {f(bot[1])}" fill="none" stroke="@blue@" stroke-width="6" stroke-linecap="round"/>')
    for x, lbl in ((Cx, "C"), (Fx, "F"), (Vx, "V")):
        b += [dot((x, ax), 4.5, "@yellow@"), text(x, ax + 26, lbl, 19, "@yellow@", "middle", bold=True)]
